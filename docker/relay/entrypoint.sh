#!/bin/sh
# phantom-relay entrypoint
#
# Если /config/relay.toml нет — копируем шаблон и рендерим из ENV.
# Если есть — стартуем как есть.

set -eu

CONFIG_DIR="${CONFIG_DIR:-/config}"
RELAY_TOML="${CONFIG_DIR}/relay.toml"

mkdir -p "$CONFIG_DIR"

if [ ! -f "$RELAY_TOML" ]; then
    echo "[bootstrap] $RELAY_TOML missing — generating from env"

    if [ -z "${UPSTREAM_ADDR:-}" ]; then
        echo "[bootstrap] FATAL: UPSTREAM_ADDR must be set on first boot (e.g. 89.110.109.128:8443)" >&2
        exit 1
    fi
    if [ -z "${EXPECTED_SNI:-}" ]; then
        echo "[bootstrap] FATAL: EXPECTED_SNI must be set on first boot — the exit's SNI that clients send (e.g. tls.nl2.example.com)" >&2
        exit 1
    fi
    # Контейнер публикует :443 наружу — без fallback-серта чужой SNI получает
    # мгновенный обрыв, что выглядит как блок ТСПУ, а не как сайт. Режим drop
    # (без серта) — только за nginx stream: тогда relay.toml пишется руками.
    if [ -z "${FALLBACK_CERT:-}" ] || [ -z "${FALLBACK_KEY:-}" ]; then
        echo "[bootstrap] FATAL: FALLBACK_CERT and FALLBACK_KEY must be set (LE cert of the relay's own name)." >&2
        echo "[bootstrap]        Behind nginx stream only: put your own relay.toml without cert_path/key_path into $CONFIG_DIR." >&2
        exit 1
    fi

    LISTEN_ADDR="${LISTEN_ADDR:-0.0.0.0:5443}"

    cat > "$RELAY_TOML" <<EOF
# Generated by docker entrypoint on first boot.

listen_addr   = "${LISTEN_ADDR}"
upstream_addr = "${UPSTREAM_ADDR}"
expected_sni  = "${EXPECTED_SNI}"

# Re-read on every fallback connection — renewals need no restart.
cert_path = "${FALLBACK_CERT}"
key_path  = "${FALLBACK_KEY}"
EOF
    echo "[bootstrap] Wrote $RELAY_TOML"
else
    echo "[entrypoint] Found existing $RELAY_TOML — skipping bootstrap"
fi

exec phantom-relay --config "$RELAY_TOML"
